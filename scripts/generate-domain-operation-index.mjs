import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = process.env.SAMURAI_REPO_ROOT
  ? path.resolve(process.env.SAMURAI_REPO_ROOT)
  : path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const readSource = (file) => {
  try {
    return readFileSync(file, "utf8");
  } catch (error) {
    throw new Error(`domain_operation_source_read_failed:${path.relative(root, file)}`, { cause: error });
  }
};
const sourceRoot = path.join(root, "packages/domain-operations/src");
const operationsRoot = path.join(sourceRoot, "operations");
const generatedRoot = path.join(sourceRoot, "generated");

const modules = filesUnder(operationsRoot)
  .filter((file) => file.endsWith(".operation.ts"))
  .map(readOperationModule)
  .sort((left, right) => left.id.localeCompare(right.id));

const duplicate = modules.find((module, index) => index > 0 && modules[index - 1].id === module.id);
if (duplicate) throw new Error(`duplicate_domain_operation_id:${duplicate.id}`);

const indexLines = [
  "// Generated by scripts/generate-domain-operation-index.mjs. Do not edit.",
  'import type { OperationDefinition } from "../definition/index.js";',
  ...modules.map((module, index) => `import operation${index} from "${module.importPath}";`),
  "",
  "export const operationDefinitions: readonly OperationDefinition[] = Object.freeze([",
  ...modules.map((_module, index) => `  operation${index},`),
  "]);",
  ""
];

const binderLines = [
  "// Generated by scripts/generate-domain-operation-index.mjs. Do not edit.",
  'import type { OperationDefinition, OperationHandler } from "../definition/index.js";',
  ...modules.map((module, index) => `import operation${index}, { type ${module.portsType} } from "${module.importPath}";`),
  "",
  "export interface DomainOperationPorts {",
  ...modules.map((module) => `  ${JSON.stringify(module.id)}: ${module.portsType};`),
  "}",
  "",
  "export interface BoundOperationDefinition {",
  "  definition: OperationDefinition;",
  "  handler: OperationHandler<unknown, unknown>;",
  "}",
  "",
  "export function bindOperationDefinitions(ports: DomainOperationPorts): readonly BoundOperationDefinition[] {",
  "  return Object.freeze([",
  ...modules.map((module, index) => `    Object.freeze({ definition: operation${index}, handler: operation${index}.createHandler(ports[${JSON.stringify(module.id)}]) }),`),
  "  ]);",
  "}",
  ""
];

const outputs = new Map([
  [path.join(generatedRoot, "operation-index.generated.ts"), `${indexLines.join("\n")}\n`],
  [path.join(generatedRoot, "operation-binder.generated.ts"), `${binderLines.join("\n")}\n`]
]);
if (process.argv.includes("--check")) {
  for (const [file, expected] of outputs) {
    if (readSource(file) !== expected) throw new Error(`generated_domain_operation_drift:${path.basename(file)}`);
  }
  process.stdout.write(`verified ${modules.length} generated domain operation bindings\n`);
} else {
  for (const [file, content] of outputs) writeFileSync(file, content);
  process.stdout.write(`generated ${modules.length} domain operation bindings\n`);
}

function readOperationModule(file) {
  const relative = path.relative(sourceRoot, file).replaceAll(path.sep, "/").replace(/\.ts$/, ".js");
  const importPath = `../${relative.replace(/^operations\//, "operations/")}`;
  const source = readSource(file);
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TS);
  const ports = ast.statements.find((statement) =>
    ts.isInterfaceDeclaration(statement)
      && statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)
      && statement.name.text.endsWith("Ports"));
  if (!ports || !ts.isInterfaceDeclaration(ports)) throw new Error(`operation_ports_interface_missing:${relative}`);
  const definitions = allNodes(ast).filter((node) => ts.isCallExpression(node)
    && ts.isCallExpression(node.expression)
    && ts.isIdentifier(node.expression.expression)
    && ["defineCommand", "defineQuery"].includes(node.expression.expression.text));
  if (definitions.length !== 1) throw new Error(`operation_definition_count:${relative}:${definitions.length}`);
  const configuration = definitions[0].arguments[0];
  if (!configuration || !ts.isObjectLiteralExpression(configuration)) throw new Error(`operation_definition_object_missing:${relative}`);
  const metadataObjects = [configuration, ...configuration.properties.flatMap((property) =>
    ts.isSpreadAssignment(property) && ts.isObjectLiteralExpression(property.expression) ? [property.expression] : [])];
  const ids = metadataObjects.flatMap((object) => object.properties.flatMap((property) =>
    ts.isPropertyAssignment(property)
      && (ts.isIdentifier(property.name) || ts.isStringLiteral(property.name))
      && property.name.text === "id"
      && ts.isStringLiteral(property.initializer)
      ? [property.initializer.text]
      : []));
  if (ids.length !== 1) throw new Error(`operation_id_count:${relative}:${ids.length}`);
  const id = ids[0];
  return { id, importPath, portsType: ports.name.text };
}

function allNodes(rootNode) {
  const result = [];
  const visit = (node) => {
    result.push(node);
    ts.forEachChild(node, visit);
  };
  visit(rootNode);
  return result;
}

function filesUnder(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name);
    return entry.isDirectory() ? filesUnder(fullPath) : [fullPath];
  });
}
